export function t(key: string, params?: Record<string, string | number>): string {
  let s: string
  if (lang.value === 'en') s = en[key] ?? enZh[key] ?? zh[key] ?? key
  else s = zh[key] ?? key
  if (params) for (const k of Object.keys(params)) s = s.replaceAll(`{${k}}`, String(params[k]))
  return s
}
